    "    var groups = {};\n"
    "    try {\n"
    "      groups = JSON.parse(localStorage.getItem('mr-groups') || '{}');\n"
    "    } catch(e) {}\n\n"
    "    var checkboxes = routers.map(function(r) {\n"
    "      return '<label style=\"display:flex;align-items:center;gap:8px;padding:4px 0;'+\n"
