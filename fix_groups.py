    "    };\n"
    "    /* Зняти всі */\n"
    "    document.getElementById('mr-select-none').onclick = function() {\n"
    "      panel.querySelectorAll('.mr-check').forEach(function(c) { c.checked = false; });\n"
    "    };\n"
    "    /* Зберегти групу */\n"
    "    document.getElementById('mr-save-group').onclick = function() {\n"
