    "    }\n\n"
    "    /* Хелпер — отримати вибрані ID */\n"
    "    function getCheckedIds() {\n"
    "      return Array.from(panel.querySelectorAll('.mr-check:checked'))\n"
    "        .map(function(c) { return c.dataset.id; });\n"
    "    }\n\n"
